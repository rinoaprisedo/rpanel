import client from './client'

export const getDockerStatus = () => client.get('/docker/status').then((r) => r.data)
export const installDocker = () => client.post('/docker/install', null, { timeout: 2400000 }).then((r) => r.data)
export const getContainers = () => client.get('/docker/containers').then((r) => r.data)
export const runContainer = (d) => client.post('/docker/containers', d, { timeout: 900000 }).then((r) => r.data)
export const containerAction = (id, action) => client.post(`/docker/containers/${id}/${action}`).then((r) => r.data)
export const removeContainer = (id) => client.delete(`/docker/containers/${id}`).then((r) => r.data)
export const getContainerLogs = (id, lines = 300) => client.get(`/docker/containers/${id}/logs`, { params: { lines } }).then((r) => r.data)
export const getImages = () => client.get('/docker/images').then((r) => r.data)
export const pullImage = (image) => client.post('/docker/images/pull', { image }, { timeout: 1300000 }).then((r) => r.data)
export const removeImage = (id) => client.delete('/docker/images', { params: { id } }).then((r) => r.data)
export const getProjects = () => client.get('/docker/compose').then((r) => r.data)
export const getProject = (name) => client.get(`/docker/compose/${name}`).then((r) => r.data)
export const createProject = (name, content) => client.post('/docker/compose', { name, content }).then((r) => r.data)
export const updateProject = (name, content) => client.put(`/docker/compose/${name}`, { name, content }).then((r) => r.data)
export const projectUp = (name) => client.post(`/docker/compose/${name}/up`, null, { timeout: 1300000 }).then((r) => r.data)
export const projectDown = (name) => client.post(`/docker/compose/${name}/down`, null, { timeout: 400000 }).then((r) => r.data)
export const projectPS = (name) => client.get(`/docker/compose/${name}/ps`).then((r) => r.data)
export const projectLogs = (name, lines = 300) => client.get(`/docker/compose/${name}/logs`, { params: { lines } }).then((r) => r.data)
export const deleteProject = (name) => client.delete(`/docker/compose/${name}`).then((r) => r.data)
export const getDockerOverview = () => client.get('/docker/overview').then((r) => r.data)
export const getDockerStats = () => client.get('/docker/stats', { timeout: 45000 }).then((r) => r.data)
